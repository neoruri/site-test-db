-- -----------------------------------------------------
-- 1. 현재 관리자 목록
-- -----------------------------------------------------
--
-- admins 에는 계정 id 만 있어서, auth.users 와 이어야 이메일이 보입니다.

select u.email            as "이메일",
       a.memo             as "메모",
       u.created_at       as "계정 생성일",
       u.last_sign_in_at  as "마지막 로그인"
from admins a
join auth.users u on u.id = a.user_id
order by u.created_at;


-- -----------------------------------------------------
-- 2. 전체 계정 목록 (관리자 여부 표시)
-- -----------------------------------------------------
--
-- 관리자가 아닌 계정이 있는지 확인할 때.
-- 회원가입이 열려 있으면 모르는 계정이 생길 수 있습니다.

select u.email       as "이메일",
       u.created_at  as "가입일",
       case when a.user_id is null then '' else '관리자' end as "구분"
from auth.users u
left join admins a on a.user_id = u.id
order by u.created_at desc;


