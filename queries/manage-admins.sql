--  `admins` 테이블에 행이 있으면 관리자입니다.
--  이 명단에 없으면 로그인을 해도 신청 내역을 볼 수 없습니다.
--
--  ⚠️ 이 테이블에는 INSERT/DELETE 권한이 아무에게도 없습니다.
--     추가·제거는 여기(SQL Editor, 관리자 권한)에서만 가능합니다.
--     의도된 설계입니다 — 앱에서 관리자를 만들 수 있으면 위험합니다.
