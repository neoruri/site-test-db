#!/bin/bash
# =====================================================
#  Supabase DB 백업 스크립트
# =====================================================
#
#  하는 일:
#    1. .env 에서 접속 정보를 읽는다
#    2. pg_dump 로 데이터를 SQL 로 뽑는다
#    3. 압축하고 날짜를 붙여 저장한다
#    4. 제대로 만들어졌는지 확인한다   ← 이게 핵심
#    5. 오래된 백업을 지운다
#
#  사용법:
#    ~/site-backup/backup-db.sh
#
#  ⚠️ 이 스크립트에는 비밀이 없습니다. 접속 정보는 ~/site-backup/.env 에만 있고,
#     그 파일은 git 밖에 있으며 권한이 600 입니다.
# =====================================================

# -e : 명령이 하나라도 실패하면 즉시 중단
# -u : 정의되지 않은 변수를 쓰면 오류
# -o pipefail : 파이프 중간이 실패해도 잡아냄
#
# 백업 스크립트에 이게 없으면, 중간이 실패해도 계속 진행해서
# '빈 파일을 백업이라고 저장하는' 사고가 납니다.
set -euo pipefail

BASE="$HOME/site-backup"
OUT="$BASE/output"


# -----------------------------------------------------
# 1. 접속 정보 불러오기
# -----------------------------------------------------
if [ ! -f "$BASE/.env" ]; then
  echo "오류: $BASE/.env 파일이 없습니다."
  exit 1
fi

# set -a : 이후 읽는 변수를 다른 프로그램(pg_dump)에도 전달되게 표시
set -a
. "$BASE/.env"
set +a

: "${PGHOST:?PGHOST 가 .env 에 없습니다}"
: "${PGUSER:?PGUSER 가 .env 에 없습니다}"
KEEP_DAYS="${KEEP_DAYS:-30}"


# -----------------------------------------------------
# 1-1. 쓸 pg_dump 고르기
# -----------------------------------------------------
#
# pg_dump 버전은 서버 버전보다 같거나 높아야 합니다. 낮으면 거부됩니다.
# (Supabase 는 PostgreSQL 17, Ubuntu 24.04 기본 패키지는 16)
#
# 여러 버전이 설치돼 있으면 가장 높은 것을 고릅니다.
# sort -V 는 버전 번호 순으로 정렬합니다 (일반 정렬은 10 이 9 보다 앞에 옴).

PG_DUMP=$(ls -d /usr/lib/postgresql/*/bin/pg_dump 2>/dev/null | sort -V | tail -1 || true)
PG_DUMP="${PG_DUMP:-$(command -v pg_dump)}"

if [ -z "$PG_DUMP" ]; then
  echo "오류: pg_dump 를 찾을 수 없습니다."
  exit 1
fi


# -----------------------------------------------------
# 2. 백업 실행
# -----------------------------------------------------
mkdir -p "$OUT"

STAMP=$(date +%Y-%m-%d_%H%M)
FILE="$OUT/db_${STAMP}.sql"

echo "[1/4] 백업 중... ($PGHOST)"
echo "      사용: $PG_DUMP ($("$PG_DUMP" --version | awk '{print $3}'))"

# --schema=public  : 우리가 만든 테이블만 (posts, applications, admins)
# --no-owner       : 소유자 정보 제외 — 다른 환경에 복구할 때 충돌을 막음
# --no-privileges  : 권한(GRANT) 정보 제외 — 구조는 db/ 마이그레이션에 있음
"$PG_DUMP" --schema=public --no-owner --no-privileges > "$FILE"


# -----------------------------------------------------
# 3. 검증  ← 가장 중요한 단계
# -----------------------------------------------------
#
# "백업을 만들었다"와 "쓸 수 있는 백업이 있다"는 다릅니다.
# 실패한 백업은 대개 0바이트이거나 내용이 비어 있는데,
# 확인하지 않으면 몇 달 뒤 복구하려 할 때 알게 됩니다.

echo "[2/4] 검증 중..."

SIZE=$(stat -c%s "$FILE")
if [ "$SIZE" -lt 1000 ]; then
  echo "오류: 백업 파일이 너무 작습니다 (${SIZE} 바이트). 실패로 간주합니다."
  rm -f "$FILE"
  exit 1
fi

# 테이블 생성문이 실제로 들어 있는지 확인
if ! grep -q "CREATE TABLE" "$FILE"; then
  echo "오류: 백업에 테이블 정의가 없습니다. 실패로 간주합니다."
  rm -f "$FILE"
  exit 1
fi

ROWS=$(grep -c "^INSERT INTO\|^COPY " "$FILE" || true)
echo "      크기 ${SIZE} 바이트 · 데이터 블록 ${ROWS}개"


# -----------------------------------------------------
# 4. 압축 + 권한
# -----------------------------------------------------
echo "[3/4] 압축 중..."

gzip "$FILE"
FILE="${FILE}.gz"

# 백업 파일에는 이름·연락처가 들어 있습니다. 나만 읽을 수 있게.
chmod 600 "$FILE"


# -----------------------------------------------------
# 5. 오래된 백업 정리
# -----------------------------------------------------
#
# 세대 관리: 최신 것만 두면 '어제 이미 망가진 데이터'를 백업한 경우
# 되돌릴 방법이 없습니다. 그래서 여러 날짜를 겹쳐서 보관합니다.

echo "[4/4] ${KEEP_DAYS}일 지난 백업 정리 중..."

DELETED=$(find "$OUT" -name "db_*.sql.gz" -mtime "+${KEEP_DAYS}" -print -delete | wc -l)
echo "      ${DELETED}개 삭제"


# -----------------------------------------------------
# 결과
# -----------------------------------------------------
echo
echo "완료: $FILE"
echo "보관 중인 백업: $(find "$OUT" -name 'db_*.sql.gz' | wc -l)개"
