-- =====================================================
-- 003. applications — 전화번호 형식 제약
-- 실행일: 2026-09-14
-- =====================================================
--
-- 화면(HTML·JavaScript)에서 하는 검사는 전부 우회 가능합니다.
-- 브라우저를 안 쓰고 API 를 직접 부르면 그냥 통과합니다.
--
--   curl -X POST .../applications -d '{"phone":"asdfasdfasd"}'
--   → 제약이 없으면 201 로 그대로 들어감
--
-- 그래서 DB 에 형식을 강제합니다. 이게 진짜 방어입니다.
-- =====================================================


-- -----------------------------------------------------
-- ① 기존 데이터 정리 (구조가 아니라 '데이터'를 고치는 작업)
-- -----------------------------------------------------
--
-- ⚠️ 이 단계를 건너뛰면 ② 가 실패합니다.
--    이미 '010-0000-0000' 처럼 하이픈이 든 데이터가 있는데,
--    "숫자만" 이라는 규칙을 걸면 기존 데이터가 규칙을 위반하기 때문입니다.
--
--    regexp_replace(대상, 찾을것, 바꿀것, 'g')
--      [^0-9] = 숫자가 아닌 것,  'g' = 전부(global)

update applications
set phone = regexp_replace(phone, '[^0-9]', '', 'g');


-- -----------------------------------------------------
-- ② 형식 제약 추가 (구조 변경)
-- -----------------------------------------------------
--
--   ~            = 정규식과 일치하는가 (PostgreSQL 연산자)
--   ^ ... $      = 문자열의 시작과 끝. 전체가 조건에 맞아야 함
--   [0-9]{10,11} = 숫자 10~11 자리
--
--   phone_digits_only 는 제약에 붙인 이름입니다. 지울 때 이 이름으로 지목합니다.

alter table applications
  add constraint phone_digits_only
  check (phone ~ '^[0-9]{10,11}$');


-- 되돌리려면:
--   alter table applications drop constraint phone_digits_only;


-- =====================================================
-- 배운 것 — 검증은 세 겹이고, 앞의 두 겹은 가짜다
-- =====================================================
--
--   1. JavaScript  → 타이핑하는 순간 숫자만 남김   (개발자도구로 제거 가능)
--   2. HTML pattern → 제출할 때 형식 검사          (속성 지우면 끝)
--   3. DB CHECK     → 저장할 때 형식 강제          ← 우회 불가
--
--   앞의 두 겹은 '친절함'이고, 세 번째만 '방어'입니다.
--   브라우저 안에서 일어나는 일은 전부 사용자가 바꿀 수 있습니다.
--
--   확인 방법:
--     curl -X POST .../applications -d '{"name":"x","phone":"asdfasdfasd"}'
--     → 400 violates check constraint "phone_digits_only"
--
--   구조와 데이터는 별개다:
--     CREATE TABLE 은 한 번뿐. 이후 변경은
--     ALTER(구조)와 UPDATE(데이터)로 나눠서 한다.
-- =====================================================
