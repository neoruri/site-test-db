-- =====================================================
-- 005. applications — 조회 조건 강화
--      "로그인한 사람" → "관리자 명단에 있는 사람"
-- 실행일: 2026-09-14
-- =====================================================
--
-- 002 에서 만든 정책은 로그인만 하면 통과였습니다.
-- 004 에서 만든 명단을 조건으로 써서 진짜 관리자만 통과하게 바꿉니다.
-- =====================================================


-- -----------------------------------------------------
-- ① 느슨한 기존 정책을 먼저 지운다
-- -----------------------------------------------------
--
-- ⚠️ 이 단계를 건너뛰면 아무 효과가 없습니다.
--    정책 여러 개는 OR 로 합쳐지기 때문에,
--    기존 정책이 계속 "로그인만 하면 OK" 라고 허용합니다.

drop policy "로그인한 사람만 조회" on applications;


-- -----------------------------------------------------
-- ② 관리자 명단을 조건으로 하는 정책
-- -----------------------------------------------------

create policy "관리자만 조회"
on applications for select
to authenticated
using ( exists (select 1 from admins where user_id = auth.uid()) );

-- to authenticated       → 인증(Authentication): 로그인은 했는가   (문 앞)
-- using (exists ...)     → 인가(Authorization):  명단에 있는가     (방 안)
-- auth.uid()             → 지금 요청 보낸 사람의 계정 id


-- =====================================================
-- 검증 방법 — 인증과 인가가 정말 분리돼 있는가
-- =====================================================
--
-- 1) 로그인한 채로 명단에서 본인을 제거한다
--
--      delete from admins
--      where user_id = (select id from auth.users where email = '주소@example.com');
--
-- 2) 관리자 페이지에서 '새로고침' 버튼을 누른다 (로그아웃하지 않음)
--
--    결과: 로그인은 그대로인데 목록이 비어 있음.
--          오류가 아니라 빈 결과입니다 — RLS 는 "권한 없음"이 아니라
--          "그런 행이 없음" 으로 답하기 때문입니다.
--
-- 3) 다시 등록하면 목록이 돌아온다
--
--    → 코드는 한 줄도 바뀌지 않았습니다. 바뀐 건 명단의 행 하나뿐입니다.
--      "로그인했다"와 "권한이 있다"는 다른 말입니다.
--
--
-- 로그인 없이 API 를 직접 부르면:
--
--   curl -s ".../rest/v1/applications?select=*" -H "apikey: sb_publishable_..."
--   → 401 permission denied
--
--   브라우저도 앱도 안 거쳤는데 막힙니다.
--   화면을 감추는 것은 보안이 아니고, 막는 것은 RLS 입니다.
-- =====================================================


-- =====================================================
-- 현재 applications 의 최종 권한 구성
-- =====================================================
--
--   명령      GRANT                  RLS 정책
--   ------------------------------------------------------------
--   INSERT    anon, authenticated    with check (true)
--   SELECT    authenticated          exists(admins where user_id = auth.uid())
--   UPDATE    (없음)                 (없음)  → 차단
--   DELETE    (없음)                 (없음)  → 차단
--
--   추가로 CHECK 제약: phone ~ '^[0-9]{10,11}$'
-- =====================================================
