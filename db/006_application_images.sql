--    Storage → New bucket
--      Name                : applications
--      Public bucket       : 끄기 (Private)
--      File size limit     : 5 MB
--      Allowed MIME types  : image/jpeg, image/png, image/webp
--
--    크기·형식 제한을 버킷에 거는 이유:
--    화면에서 하는 검사는 우회 가능합니다. 서버 쪽 제한이 진짜 방어입니다.
--    (전화번호 CHECK 제약과 같은 원리 — 003 참조)
-- =====================================================


-- -----------------------------------------------------
-- ① 이미지 경로를 담을 열 추가
-- -----------------------------------------------------
--
-- 파일 자체는 Storage 에 두고, 테이블에는 '위치'만 저장합니다.
-- 파일을 DB 에 직접 넣으면 느려지고 비쌉니다.

alter table applications add column image_path text;

-- null 을 허용합니다 — 첨부는 선택 사항이므로.


-- -----------------------------------------------------
-- ② Storage 정책 — 업로드는 누구나
-- -----------------------------------------------------
--
-- 파일 권한도 테이블과 똑같이 정책으로 통제합니다.
-- 대상이 '행'에서 '파일'로 바뀌었을 뿐입니다.
--
-- storage.objects 는 Supabase 가 파일 목록을 관리하는 테이블입니다.

create policy "누구나 첨부 업로드"
on storage.objects for insert
to anon, authenticated
with check ( bucket_id = 'applications' );


-- -----------------------------------------------------
-- ③ Storage 정책 — 조회는 관리자만
-- -----------------------------------------------------
--
-- 005 의 applications 조회 정책과 같은 조건을 씁니다.
-- 신청 내역을 볼 수 있는 사람이 첨부도 볼 수 있어야 하니까요.

create policy "관리자만 첨부 조회"
on storage.objects for select
to authenticated
using (
  bucket_id = 'applications'
  and exists (select 1 from admins where user_id = auth.uid())
);

-- UPDATE / DELETE 정책은 만들지 않습니다 → 차단.
-- 올린 파일은 아무도 수정·삭제할 수 없습니다.


-- =====================================================
-- 배운 것
-- =====================================================
--
-- 1. 파일도 RLS 로 보호된다
--    테이블과 같은 방식입니다. 버킷을 Private 으로 만들고 정책을 걸면,
--    URL 을 알아도 정책을 통과하지 못하면 받을 수 없습니다.
--
-- 2. "보기"와 "다운로드"는 구분되지 않는다
--    브라우저에 이미지가 보인다는 건 이미 파일이 전송됐다는 뜻입니다.
--    그래서 정책도 SELECT 하나로 둘을 함께 통제합니다.
--
-- 3. Private 파일은 Signed URL 로 보여준다
--    유효기간이 있는 임시 주소를 발급받아 표시합니다.
--    주소가 유출돼도 시간이 지나면 쓸 수 없습니다.
--
-- 4. 파일명은 서버가 정한다
--    사용자가 올린 이름을 그대로 쓰면
--      - 같은 이름끼리 덮어쓰기
--      - 경로 조작 시도 (../)
--      - 한글·특수문자 문제
--    가 생깁니다. 무작위 이름을 새로 지어서 저장합니다.
